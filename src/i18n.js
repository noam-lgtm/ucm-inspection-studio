export function t(key, params) {
  let text = HE[key];
  if (text === undefined) return key;
  if (typeof text !== 'string') return text;
  if (params) for (const [k, v] of Object.entries(params)) text = text.split('{' + k + '}').join(String(v));
  return text;
}
